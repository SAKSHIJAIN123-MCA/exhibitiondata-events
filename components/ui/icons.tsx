import type { ReactNode, SVGProps } from "react";

/**
 * Small inline icon set (stroke icons, 24x24 grid). Inline SVG avoids adding
 * an icon library. Icons are decorative, so they are hidden from screen
 * readers; put a text label next to them.
 */
function Icon({
  children,
  ...props
}: SVGProps<SVGSVGElement> & { children: ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...props}
    >
      {children}
    </svg>
  );
}

type IconProps = SVGProps<SVGSVGElement>;

